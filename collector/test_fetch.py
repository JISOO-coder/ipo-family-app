def test_html_to_text_and_ids():
    h = "<html><script>x=1</script><body><b>확정공모가</b> <b>18,500</b> 원</body></html>"
    assert html_to_text(h) == "확정공모가 18,500 원"
    page = '<a href="http://www.38.co.kr/html/fund/?o=v&no=2326&l=&page=1">a</a>' \
           '<a href="/html/fund/index.htm?o=v&no=2340&l=&page=1">b</a>' \
           '<a href="/html/fund2/?o=v&no=1830">x</a>'
    assert list_ids(page) == [2340, 2326]

