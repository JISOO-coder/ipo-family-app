def test_total_row_with_missing_percent_sign():
    # 합계 줄 지분율에 %가 빠진 칸이 있어도 같은 값이 나와야 함 (제이피아이헬스케어 표 모양)
    t = MSBIO.replace("20,855,340 76.67%", "20,855,340 76.67")
    assert abs(parse_detail(t)["existing_holder_ratio"] - 39.5) < 0.01

def test_public_subtotal_row_used_when_no_esop_word():
    d = parse_detail(MSBIO)
    assert abs(d["existing_holder_ratio"] - 39.5) < 0.01    # (6,347,310 − 3,840,000) ÷ 6,347,310
